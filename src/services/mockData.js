/**
 * Universal pagination and filter helper for mock collections
 */
export const paginateCollection = (items, { page = 1, pageSize = 10, search = '', filterKey, filterVal, sortBy, sortDirection = 'asc' } = {}) => {
  let filtered = [...items];

  // Apply search query
  if (search && search.trim() !== '') {
    const q = search.toLowerCase().trim();
    filtered = filtered.filter((item) =>
      Object.values(item).some((val) =>
        String(val).toLowerCase().includes(q)
      )
    );
  }

  // Apply specific key-value filter
  if (filterKey && filterVal && filterVal !== 'all') {
    filtered = filtered.filter(
      (item) => String(item[filterKey]).toLowerCase() === String(filterVal).toLowerCase()
    );
  }

  // Apply sorting
  if (sortBy) {
    filtered.sort((a, b) => {
      const aVal = a[sortBy];
      const bVal = b[sortBy];
      if (aVal === bVal) return 0;
      if (aVal === undefined || aVal === null) return 1;
      if (bVal === undefined || bVal === null) return -1;
      const res = aVal > bVal ? 1 : -1;
      return sortDirection === 'desc' ? -res : res;
    });
  }

  const totalRecords = filtered.length;
  const totalPages = Math.max(1, Math.ceil(totalRecords / pageSize));
  const validPage = Math.min(Math.max(1, page), totalPages);
  const startIndex = (validPage - 1) * pageSize;
  const data = filtered.slice(startIndex, startIndex + pageSize);

  return {
    success: true,
    data,
    pagination: {
      page: validPage,
      pageSize,
      totalRecords,
      totalPages,
      hasNext: validPage < totalPages,
      hasPrev: validPage > 1,
    },
  };
};

